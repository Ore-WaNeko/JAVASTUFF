CREATE TABLE IF NOT EXISTS app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS loan (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lender_id BIGINT NOT NULL REFERENCES app_user(id), borrower_id BIGINT NOT NULL REFERENCES app_user(id),
 initiator_id BIGINT NOT NULL REFERENCES app_user(id), status VARCHAR(30) NOT NULL,
 current_version INT NOT NULL,
 CHECK(lender_id <> borrower_id),
 CHECK(initiator_id IN (lender_id,borrower_id)),
 CHECK(status='PENDING_TERMS' AND current_version=1)
);
CREATE TABLE IF NOT EXISTS loan_terms (
 loan_id BIGINT NOT NULL REFERENCES loan(id), version INT NOT NULL,
 kind VARCHAR(10) NOT NULL, amount DECIMAL(14,2), currency VARCHAR(3), item_description VARCHAR(200),
 start_date DATE NOT NULL, due_date DATE NOT NULL, proposed_by BIGINT NOT NULL REFERENCES app_user(id),
 PRIMARY KEY(loan_id,version), CHECK(version=1 AND start_date <= due_date),
 CHECK((kind='MONEY' AND amount IS NOT NULL AND amount>0 AND currency IS NOT NULL AND item_description IS NULL) OR
       (kind='ITEM' AND amount IS NULL AND currency IS NULL AND item_description IS NOT NULL))
);
